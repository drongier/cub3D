int	font_width(const char *s, int scale)
{
	int	n;

	n = (int)strlen(s);
	if (n == 0)
		return (0);
	return ((n * FONT_ADVANCE - 1) * scale);
}

static void	draw_glyph(uint32_t *fb, int fb_w, int fb_h, t_text t, int g)
{
	int	gx;
	int	gy;
	int	x;
	int	y;

	gy = -1;
	while (++gy < FONT_H * t.scale)
	{
		y = t.y + gy;
		gx = -1;
		while (y >= 0 && y < fb_h && ++gx < FONT_W * t.scale)
		{
			x = t.x + gx;
			if (x >= 0 && x < fb_w
				&& g_glyphs[g][gy / t.scale][gx / t.scale] == '#')
				fb[(long)y * fb_w + x] = t.color;
		}
	}
}

void	font_draw(uint32_t *fb, int fb_w, int fb_h, t_text t, const char *s)
{
	const char	*p;

	while (*s)
	{
		p = strchr(g_chars, *s);
		if (p && *p)
			draw_glyph(fb, fb_w, fb_h, t, (int)(p - g_chars));
		t.x += FONT_ADVANCE * t.scale;
		s++;
	}
}
